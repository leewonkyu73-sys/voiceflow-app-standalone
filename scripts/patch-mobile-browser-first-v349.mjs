import fs from 'node:fs';
const file=new URL('../public/app.js',import.meta.url);
let s=fs.readFileSync(file,'utf8');
const lines=s.split('\n');
const fallbackIndex=lines.findIndex(x=>x.startsWith('function startServerSpeechFallback(){'));
const speechIndex=lines.findIndex(x=>x.startsWith('function startSpeech(){'));
if(fallbackIndex<0||speechIndex<0)throw new Error('mobile_browser_first_anchor_missing');
const fallbackBefore=lines[fallbackIndex],speechBefore=lines[speechIndex];
const old="const mobileSpeech=/Android|iPhone|iPad|iPod/i.test(navigator.userAgent||'');if(mobileSpeech){startServerSpeechFallback();state.media.stt='server';state.media.sttError='';return}const SR=window.SpeechRecognition||window.webkitSpeechRecognition;";
const next="const mobileSpeech=/Android|iPhone|iPad|iPod/i.test(navigator.userAgent||'');const mobileBrowserSpeech=/Android/i.test(navigator.userAgent||'')&&/(Chrome|Chromium)\\//i.test(navigator.userAgent||'')&&!/(EdgA|OPR)\\//i.test(navigator.userAgent||'')&&Boolean(window.SpeechRecognition||window.webkitSpeechRecognition);if(mobileSpeech&&!mobileBrowserSpeech){startServerSpeechFallback();state.media.stt='server';state.media.sttError='';return}const SR=window.SpeechRecognition||window.webkitSpeechRecognition;";
if(!speechBefore.includes(old))throw new Error('mobile_server_only_anchor_missing');
const pcTail=speechBefore.slice(speechBefore.indexOf('const SR='));
lines[speechIndex]=speechBefore.replace(old,next);
if(lines[fallbackIndex]!==fallbackBefore)throw new Error('server_fallback_changed');
if(lines[speechIndex].slice(lines[speechIndex].indexOf('const SR='))!==pcTail)throw new Error('pc_speech_tail_changed');
s=lines.join('\n');
if(!s.includes('const mobileBrowserSpeech=')||s.includes("if(mobileSpeech){startServerSpeechFallback();"))throw new Error('mobile_browser_first_contract_missing');
fs.writeFileSync(file,s);
console.log('VoiceFlow Android Chrome browser-first STT v3.4.9 applied');
